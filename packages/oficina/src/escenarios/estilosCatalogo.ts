/** No muta la lista del mundo ni duplica los estilos si ya estaban presentes. */
export function variantesConCatalogo(variantes: readonly VarianteEscenario[]): VarianteEscenario[] {
  const ids = new Set(variantes.map((v) => v.id));
  return [...variantes, ...ESTILOS_CATALOGO.filter((v) => !ids.has(v.id))];
}
