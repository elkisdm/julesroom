import type { VarianteEscenario } from './tipos';
/** Una paleta cubre las claves semánticas de ambos interiores sin alterar sus muebles ni su plano. */
function estilo(
  id: string,
  nombre: string,
  hora: number,
  piso: string,
  muro: string,
  madera: string,
  metal: string,
  acento: string,
  luz: string,
): VarianteEscenario {
  return {
    id: `catalogo-${id}`,
    nombre,
    paleta: {
      hora,
      fondo: muro,
      materiales: {
        piso,
        cemento: piso,
        hormigon: piso,
        ladrillo: muro,
        tinta: muro,
        piedra: piso,
        roble: madera,
        robleClaro: madera,
        nogal: madera,
        nogalPanel: madera,
        acero: metal,
        aceroMate: metal,
        metal,
        laton: metal,
        salvia: acento,
        salviaLaca: acento,
        terracota: acento,
        terracotaCuero: acento,
        tela: acento,
        butaca: acento,
        cuero: acento,
        alfombra: acento,
        alfombraAula: acento,
        crema: muro,
      },
      acabados: {
        piso: 0.85,
        cemento: 0.85,
        hormigon: 0.85,
        ladrillo: 0.92,
        roble: 0.6,
        nogal: 0.6,
        acero: 0.4,
        metal: 0.4,
        salvia: 0.9,
        tela: 0.9,
      },
      emisivos: { luzCalida: { color: luz, fuerza: 2.2 }, luzTenue: { color: luz, fuerza: 1.3 } },
      luces: {
        relleno: { color: luz, intensidad: 0.8 },
        lamparas: { color: luz, intensidad: 1.1 },
      },
    },
  };
}
